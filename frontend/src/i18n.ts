export type Translator = (key: string) => string;
export const translator = (lang: string): Translator => {
  const dict = lang?.startsWith('es') ? es : lang?.startsWith('fr') ? fr : en;
  return (key) => dict[key as Key] ?? key;
};

// Server responses are shared across languages. Translate known messages at the
// presentation boundary, retaining unknown diagnostics rather than hiding them.
const serverKeys: Key[] = [
  'warnEncoding', 'warnFormulas', 'warnAmbiguousDates', 'updatingSource',
  'sourceUpdateFailed', 'statusPreparing', 'statusQueueUnavailable',
  'statusInterrupted', 'statusProcessingFailed', 'statusAccessDenied',
  'statusCacheRebuild', 'statusQueryTimeout', 'statusQueryLimits',
  'statusCalculationRange', 'statusEmptyFile', 'statusInvalidTable',
  'statusWorksheetMissing', 'statusWorksheetEmpty', 'statusEncodingMismatch',
  'statusExportLimit', 'statusFilterNumber', 'statusFilterDate', 'statusFilterBoolean',
];
const serverAliases: Record<string, Key> = {
  'Waiting for dashboard processing.': 'waiting',
  'Calculating the dashboard.': 'loadingQuery',
  'The cache is rebuilding. Please try again.': 'processing',
  'The source must be revalidated before this dashboard can be displayed.': 'statusCacheRebuild',
  'The source changed. Refresh the dashboard.': 'statusSourceChanged',
  'The source was updated. Please retry the dashboard.': 'statusSourceChanged',
  'The source changed. Please retry the dashboard.': 'statusSourceChanged',
  'The source changed. Please retry the export.': 'statusSourceChanged',
  'The resource changed during preparation. Refresh the dashboard.': 'statusSourceChanged',
  'A table column is no longer available. Update the selected columns.': 'tableColumnsMissing',
};
const serverCodes: Record<string, Key> = {
  job_interrupted: 'statusInterrupted',
  queue_unavailable: 'statusQueueUnavailable',
  processing_failed: 'statusProcessingFailed',
  access_denied: 'statusAccessDenied',
  cache_corrupt: 'statusCacheRebuild',
  source_unavailable: 'statusSourceUnavailable',
  source_temporarily_unavailable: 'statusSourceTemporary',
};

export function serverMessage(message: string, t: Translator, code?: string): string {
  if (typeof message !== 'string') return t(code && serverCodes[code] ? serverCodes[code] : 'error');
  const key = serverAliases[message] ?? serverKeys.find((candidate) => en[candidate] === message);
  if (key) return t(key);
  let match = /^Choose a (x|y|series|lat|lon) column\.$/.exec(message);
  if (match) return t('fieldRequired').replace('{field}', () => t(`${match![1]}_field`));
  match = /^Column '(.+)' is no longer available\.$/.exec(message);
  if (match) return t('fieldMissing').replace('{column}', () => match![1]);
  match = /^Column '(.+)' has an incompatible type\. Update this block or its column interpretation\.$/.exec(message);
  if (match) return t('fieldIncompatible').replace('{column}', () => match![1]);
  match = /^Type override column '(.+)' is no longer available\.$/.exec(message);
  if (match) return t('warnOverrideMissing').replace('{column}', () => match![1]);
  match = /^(.*): (\d+) values could not be interpreted as (number|date|boolean|text); they are excluded from calculations and preserved in CSV export\.$/.exec(message);
  if (match) {
    const values: Record<string, string> = { column: match[1], count: match[2], type: t(match[3]) };
    return t('warnInvalidValues').replace(/\{(column|count|type)\}/g, (_, name: string) => values[name]);
  }
  const ambiguousSuffix = `: ${en.warnAmbiguousDates}`;
  if (message.endsWith(ambiguousSuffix))
    return `${message.slice(0, -ambiguousSuffix.length)}: ${t('warnAmbiguousDates')}`;
  if (code && serverCodes[code]) return t(serverCodes[code]);
  return message;
}
